// Writes src/lib/physics/mask.ts: the 10′ land/sea mask used by the offline fallback bathymetry.
//   node scripts/landmask.mjs
// Source: Natural Earth 1:10m "land" (public domain) via the world-atlas package. A cell is land
// when its centre point (the model grid node) lies inside a land polygon (even–odd scanline fill).
// The box must match DOM in src/lib/physics/constants.ts.
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const topo = require("topojson-client");
const land10 = require("world-atlas/land-10m.json");

export const BOX = { lon0: 50, lon1: 105, lat0: -30, lat1: 28 };
const d = 1 / 6;
const nx = Math.round((BOX.lon1 - BOX.lon0) / d) + 1,
  ny = Math.round((BOX.lat1 - BOX.lat0) / d) + 1;

const f = topo.feature(land10, land10.objects.land);
const geoms = f.features ? f.features.map((x) => x.geometry) : [f.geometry];
// All rings (outer and holes); even–odd filling handles lakes and enclaves.
const rings = geoms
  .flatMap((g) => (g.type === "Polygon" ? [g.coordinates] : g.coordinates))
  .flat()
  // Antarctica encircles the pole and cannot be filled in the plane; it is far outside the box anyway.
  .filter((r) => r.every(([, y]) => y > -60))
  .filter((r) => {
    let x0 = 1e9, x1 = -1e9, y0 = 1e9, y1 = -1e9;
    for (const [x, y] of r) {
      x0 = Math.min(x0, x); x1 = Math.max(x1, x); y0 = Math.min(y0, y); y1 = Math.max(y1, y);
    }
    return x1 >= BOX.lon0 - 1 && x0 <= BOX.lon1 + 1 && y1 >= BOX.lat0 - 1 && y0 <= BOX.lat1 + 1;
  });

const mask = new Uint8Array(nx * ny);
for (let j = 0; j < ny; j++) {
  const lat = BOX.lat0 + j * d;
  const xs = [];
  for (const r of rings)
    for (let k = 0; k < r.length - 1; k++) {
      const [ax, ay] = r[k],
        [bx, by] = r[k + 1];
      // Natural Earth rings are cut at ±180°; an edge that jumps across the map is not a real coastline.
      if (Math.abs(bx - ax) > 180) continue;
      if (ay > lat !== by > lat) xs.push(ax + ((lat - ay) / (by - ay)) * (bx - ax));
    }
  xs.sort((a, b) => a - b);
  for (let i = 0; i < nx; i++) {
    const lon = BOX.lon0 + i * d;
    let c = 0;
    for (const x of xs) if (x < lon) c++;
    mask[j * nx + i] = c & 1;
  }
}

const bytes = new Uint8Array(Math.ceil((nx * ny) / 8));
for (let k = 0; k < nx * ny; k++) if (mask[k]) bytes[k >> 3] |= 1 << (7 - (k & 7));
const b64 = Buffer.from(bytes).toString("base64");
const landPct = ((mask.reduce((a, b) => a + b, 0) / mask.length) * 100).toFixed(1);
writeFileSync(
  "src/lib/physics/mask.ts",
  `/* Generated by scripts/landmask.mjs. Do not edit.
 * Land/sea mask, 10 arc-minute grid over ${BOX.lon0}–${BOX.lon1}°E, ${-BOX.lat0}°S–${BOX.lat1}°N (${nx} × ${ny}), 1 bit per cell, MSB first.
 * Natural Earth 1:10m land (public domain); a node is land if it lies inside a land polygon.
 * Used only for the offline fallback bathymetry. */
export const MASK10_B64 =
  "${b64}";

export const MASK_NX = ${nx};
export const MASK_NY = ${ny};

export function decodeMask(): Uint8Array {
  const bin = atob(MASK10_B64);
  const n = MASK_NX * MASK_NY;
  const m = new Uint8Array(n);
  for (let k = 0; k < n; k++) m[k] = (bin.charCodeAt(k >> 3) >> (7 - (k & 7))) & 1;
  return m;
}
`,
);
console.log(`mask ${nx} × ${ny}, land ${landPct} %`);
